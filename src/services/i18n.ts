// 支持 {name} 占位符替换；英文缺失时回退中文，键不存在时返回键名（开发期立刻可见）
export function t(key: string, params?: Record<string, string | number>): string {
  const entry = MESSAGES[key]
  if (!entry) return key
  const index = current === 'en' ? 1 : 0
  const text = entry[index] || entry[0]
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (_match, name: string) => (params[name] === undefined ? '' : String(params[name])))
}

